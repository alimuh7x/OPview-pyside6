"""Robust parsing of Custom Graph text files: comments, delimiters, decimal commas, units, errors."""

import tempfile
import unittest
from pathlib import Path

import numpy as np

from data.text_sources import GenericTextDataSource


def _load(text: str, name: str = "data.txt", *, encoding: str = "utf-8", raw: bytes | None = None):
    path = Path(tempfile.mkdtemp()) / name
    if raw is not None:
        path.write_bytes(raw)
    else:
        path.write_text(text, encoding=encoding, newline="")
    source = GenericTextDataSource(path)
    return source, source.load()


class HeaderTests(unittest.TestCase):
    def test_plain_whitespace_header_is_unchanged(self):
        source, ok = _load("Time Stress Strain\n0 100 0.0\n1 120 0.1\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["Time", "Stress", "Strain"])
        self.assertEqual(source.series("Stress").tolist(), [100, 120])
        self.assertEqual(source.separator, "whitespace")

    def test_commented_header_gives_the_right_names_and_no_shifted_data(self):
        source, ok = _load("# time stress\n0 1.5\n1 2.5\n2 3.5\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["time", "stress"])  # not ['#', 'time']
        self.assertEqual(source.series("time").tolist(), [0.0, 1.0, 2.0])
        self.assertEqual(source.series("stress").tolist(), [1.5, 2.5, 3.5])

    def test_leading_comment_lines_before_a_normal_header_are_skipped(self):
        source, ok = _load("# generated by OpenPhase\n% another note\nTime Value\n0 1\n1 2\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["Time", "Value"])
        self.assertEqual(source.series("Value").tolist(), [1.0, 2.0])

    def test_comment_lines_between_data_rows_are_ignored(self):
        source, ok = _load("t v\n0 1\n# restart\n1 2\n")

        self.assertTrue(ok)
        self.assertEqual(source.series("t").tolist(), [0.0, 1.0])

    def test_headerless_numeric_file_gets_generated_column_names_and_keeps_every_row(self):
        source, ok = _load("0 1\n1 2\n2 3\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["Column 1", "Column 2"])
        self.assertEqual(source.series("Column 1").tolist(), [0.0, 1.0, 2.0])  # the first row is data

    def test_duplicate_header_names_are_made_unique_instead_of_merging_columns(self):
        source, ok = _load("Time Time Value\n0 10 1\n1 20 2\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["Time", "Time_2", "Value"])
        self.assertEqual(source.series("Time_2").tolist(), [10.0, 20.0])
        self.assertEqual(len(source.series("Time")), 2)  # not doubled

    def test_blank_header_names_get_a_placeholder(self):
        source, ok = _load("t, ,v\n0,5,1\n1,6,2\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["t", "Column 2", "v"])

    def test_utf8_bom_and_crlf_line_endings(self):
        source, ok = _load("Time,Value\r\n0,1\r\n1,2\r\n", encoding="utf-8-sig")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["Time", "Value"])
        self.assertEqual(source.series("Value").tolist(), [1.0, 2.0])


class DelimiterTests(unittest.TestCase):
    def test_comma_separated_file(self):
        source, ok = _load("t,s\n0,1.5\n1,2.5\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["t", "s"])
        self.assertEqual(source.separator, "comma")

    def test_semicolon_separated_file_loads(self):
        source, ok = _load("t;s\n0;1.5\n1;2.5\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["t", "s"])
        self.assertEqual(source.series("s").tolist(), [1.5, 2.5])
        self.assertEqual(source.separator, "semicolon")

    def test_semicolon_file_with_decimal_commas(self):
        source, ok = _load("t;s\n0;1,5\n1;2,5\n")

        self.assertTrue(ok)
        self.assertEqual(source.series("s").tolist(), [1.5, 2.5])

    def test_whitespace_file_with_decimal_commas_keeps_every_column(self):
        source, ok = _load("t s\n0 1,5\n1 2,5\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["t", "s"])  # the second column is no longer dropped
        self.assertEqual(source.series("s").tolist(), [1.5, 2.5])
        self.assertEqual(source.separator, "whitespace")

    def test_decimal_comma_with_exponent(self):
        source, ok = _load("t s\n0 1,5e3\n1 2,5e-1\n")

        self.assertTrue(ok)
        self.assertEqual(source.series("s").tolist(), [1500.0, 0.25])

    def test_tab_separated_file_with_spaces_inside_the_names(self):
        source, ok = _load("Time [s]\tStress [Pa]\n0\t1.5\n1\t2.5\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["Time [s]", "Stress [Pa]"])
        self.assertEqual(source.separator, "tab")

    def test_comma_file_with_spaces_after_the_commas(self):
        source, ok = _load("t, s\n0, 1.5\n1, 2.5\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["t", "s"])
        self.assertEqual(source.series("s").tolist(), [1.5, 2.5])

    def test_ragged_comma_rows_are_padded_like_the_crss_file(self):
        source, ok = _load("Time, ss_1, ss_2, Average\n0, 100, 200\n1, 110, 210\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["Time", "ss_1", "ss_2"])  # all-NaN 'Average' is dropped
        self.assertEqual(source.series("ss_1").tolist(), [100, 110])

    def test_short_rows_are_padded_with_nan_and_long_rows_truncated(self):
        source, ok = _load("a b c\n1 2 3\n4 5\n6 7 8 9\n")

        self.assertTrue(ok)
        self.assertTrue(np.isnan(source.series("c")[1]))
        self.assertEqual(source.series("c")[2], 8.0)

    def test_single_column_file(self):
        source, ok = _load("Value\n1\n2\n3\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["Value"])


class UnitsRowTests(unittest.TestCase):
    def test_units_row_is_not_data_and_is_reported(self):
        source, ok = _load("Time Stress\n[s] [Pa]\n0 1.5\n1 2.5\n")

        self.assertTrue(ok)
        self.assertEqual(source.series("Time").tolist(), [0.0, 1.0])  # no NaN row
        self.assertEqual(source.units(), {"Time": "s", "Stress": "Pa"})

    def test_units_in_parentheses(self):
        source, ok = _load("t,s\n(s),(MPa)\n0,1\n")

        self.assertTrue(ok)
        self.assertEqual(source.units(), {"t": "s", "s": "MPa"})

    def test_a_file_without_a_units_row_has_no_units(self):
        source, ok = _load("t s\n0 1\n")

        self.assertTrue(ok)
        self.assertEqual(source.units(), {})


class ValueTests(unittest.TestCase):
    def test_non_numeric_cells_become_nan_and_all_text_columns_are_dropped(self):
        source, ok = _load("t label v\n0 a 1\n1 b 2\n")

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["t", "v"])

    def test_nan_and_inf_words_parse(self):
        source, ok = _load("t v\n0 nan\n1 2\n")

        self.assertTrue(ok)
        self.assertTrue(np.isnan(source.series("v")[0]))

    def test_scientific_notation(self):
        source, ok = _load("t v\n0 1.0e+08\n1 -2.5E-3\n")

        self.assertEqual(source.series("v").tolist(), [1.0e8, -2.5e-3])


class ErrorReasonTests(unittest.TestCase):
    def test_missing_file_says_so(self):
        source = GenericTextDataSource(Path(tempfile.mkdtemp()) / "nope.txt")

        self.assertFalse(source.load())
        self.assertIn("not found", source.error.lower())

    def test_unsupported_extension_says_so(self):
        source, ok = _load("a b\n1 2\n", name="data.xyz")

        self.assertFalse(ok)
        self.assertIn(".xyz", source.error)

    def test_empty_file_says_so(self):
        source, ok = _load("\n\n")

        self.assertFalse(ok)
        self.assertIn("empty", source.error.lower())

    def test_header_only_file_explains_what_is_missing(self):
        source, ok = _load("Time Value\n")

        self.assertFalse(ok)
        self.assertIn("data row", source.error.lower())

    def test_single_line_of_numbers_explains_what_is_missing(self):
        source, ok = _load("0.1 0.2 0.3\n", name="PlasticityDiagnosis.txt")

        self.assertFalse(ok)
        self.assertTrue(source.error)

    def test_text_only_file_says_no_numeric_columns(self):
        source, ok = _load("a b\nx y\nz w\n")

        self.assertFalse(ok)
        self.assertIn("numeric", source.error.lower())

    def test_successful_load_has_no_error(self):
        source, ok = _load("a b\n1 2\n")

        self.assertTrue(ok)
        self.assertEqual(source.error, "")

    def test_non_utf8_bytes_do_not_crash_the_loader(self):
        source, ok = _load("", raw="Zeit Spannung\n0 1\n1 2\n# \xe4\xf6\n".encode("latin-1"))

        self.assertTrue(ok)
        self.assertEqual(source.columns(), ["Zeit", "Spannung"])


class ProjectFilesRegressionTests(unittest.TestCase):
    """The shipped sample files keep loading exactly as before."""

    EXPECTED_COLUMNS = {
        "CRSSFile.txt": 14,
        "CRSSGrainsFile.txt": 11,
        "DDFile.txt": 2,
        "DDGrainsFile.txt": 11,
        "NeighboInfo.dat": 12,  # headerless: see test_headerless_neighbo_file_keeps_all_columns_and_the_first_row
        "PlasticStrainFile.txt": 14,
        "SizeAveInfo.dat": 4,
        "SizeDetails.dat": 12,
        "StressStrainFile.txt": 17,
    }

    def test_sample_files_have_the_same_columns_and_rows_as_before(self):
        for name, count in self.EXPECTED_COLUMNS.items():
            source = GenericTextDataSource(Path("Project1/TextData") / name)

            self.assertTrue(source.load(), name)
            self.assertEqual(len(source.columns()), count, name)
            self.assertGreaterEqual(len(source.series(source.columns()[0])), 50, name)

    def test_headerless_neighbo_file_keeps_all_columns_and_the_first_row(self):
        # The first line is data ("0 10 5 4 ..."). The old parser used it as column names; the repeated
        # numbers then merged columns (12 became 6, with interleaved values) and the t=0 row was lost.
        source = GenericTextDataSource(Path("Project1/TextData/NeighboInfo.dat"))

        self.assertTrue(source.load())
        self.assertEqual(source.columns()[:3], ["Column 1", "Column 2", "Column 3"])
        self.assertEqual(source.series("Column 1")[:3].tolist(), [0.0, 100.0, 200.0])
        self.assertEqual(len(source.series("Column 1")), 51)

    def test_stress_strain_file_columns(self):
        source = GenericTextDataSource(Path("Project1/TextData/StressStrainFile.txt"))

        self.assertTrue(source.load())
        self.assertEqual(source.columns()[:3], ["TimeStep", "Time", "Epsilon_xx"])
        self.assertEqual(len(source.series("Sigma_xx")), 501)

    def test_the_one_line_diagnosis_file_fails_with_a_reason(self):
        source = GenericTextDataSource(Path("Project1/TextData/PlasticityDiagnosis.txt"))

        self.assertFalse(source.load())
        self.assertTrue(source.error)


if __name__ == "__main__":
    unittest.main()
